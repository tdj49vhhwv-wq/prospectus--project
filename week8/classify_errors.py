def main() -> None:
    parser = argparse.ArgumentParser(description="FP/FN 逐条误差分类")
    parser.add_argument("--details", type=Path, default=PROJECT_ROOT / "week8" / "event_eval" / "event_eval_details.csv")
    parser.add_argument("--out", type=Path, default=PROJECT_ROOT / "week8" / "error_classification.csv")
    args = parser.parse_args()

    rows = list(csv.DictReader(open(args.details, encoding="utf-8")))
    missing = []
    out_rows = []
    counts: Counter = Counter()
    per_type: defaultdict[str, Counter] = defaultdict(Counter)

    for r in rows:
        if r["status"] == "TP":
            continue
        key = (r["role"], r["stock_code"], r["date"], r["type_code"], r["context"])
        if key not in CLASSIFICATION:
            missing.append((key, r["role"]))
            continue
        category, note = CLASSIFICATION[key]
        counts[category] += 1
        per_type[f"{r['role']}:{r['type_code']}"][category] += 1
        out_rows.append({
            "role": r["role"],
            "stock_code": r["stock_code"],
            "date": r["date"],
            "date_type": r["date_type"],
            "type_code": r["type_code"],
            "context": r["context"],
            "status": r["status"],
            "category": category,
            "note": note,
        })

    if missing:
        for key, role in missing:
            print("MISSING:", role, key)
        raise SystemExit(1)

    with open(args.out, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(out_rows[0].keys()), lineterminator="\n")
        writer.writeheader()
        writer.writerows(out_rows)

    print(f"已分类 {len(out_rows)} 条（FP {sum(1 for r in out_rows if r['role']=='auto')} + "
          f"FN {sum(1 for r in out_rows if r['role']=='gold')}）")
    print("分类统计:")
    for category, n in counts.most_common():
        print(f"  {category}: {n}")
    print(f"输出: {args.out}")


if __name__ == "__main__":
    main()
